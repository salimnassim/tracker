package tracker

import "testing"

func Test(t *testing.T) {
	t.Run("ok", func(t *testing.T) {
		bytes := []byte{
			0x41, 0x72, 0x71, 0x01, 0x98, 0x0, 0x0, 0x0, // Connection ID
			0x0, 0x0, 0x0, 0x1, // Action (Announce)
			0x12, 0x34, 0x56, 0x78, // Transaction ID
			0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x11, 0x22, 0x33,
			0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB, 0xCC, 0xDD, // Info Hash
			0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99,
			0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x11, 0x22, 0x33, // Peer ID
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05, // Downloaded (5 bytes)
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0A, // Left (10 bytes)
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // Uploaded (0 bytes)
			0x00, 0x00, 0x00, 0x02, // Event (Started)
			0x00, 0x00, 0x00, 0x00, // IP Address (0 = auto-detect)
			0xAB, 0xCD, 0x12, 0x34, // Key
			0xFF, 0xFF, 0xFF, 0xFF, // Num Want (-1)
			0x12, 0x34, // Port (4660 in decimal)
		}
		req := &announceRequest{}
		err := req.unpack(bytes)
		if err != nil {
			t.Error(err)
		}
	})
}

func FuzzAnnounceUnpack(f *testing.F) {
	f.Fuzz(func(t *testing.T, data []byte) {
		req := &announceRequest{}
		_ = req.unpack(data)
	})
}
